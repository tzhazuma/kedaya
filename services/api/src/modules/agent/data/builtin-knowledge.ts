import type { KnowledgeDoc } from '../domain/agent.domain';

/**
 * 内置知识库（随版本发布，永远可用）。
 *
 * 为什么需要它，而不是"只读数据库里的 FAQ"：
 *   · 新部署 / 空库时 FAQ 表是空的，agent 不能因此变成哑巴；
 *   · 使用指南属于**产品事实**，跟代码一起做 code review 比放在数据库里手工维护更可靠；
 *   · 它同时是 RAG 的**兜底**：检索不到任何 FAQ 时，指南仍在。
 *
 * 边界：这里只写**对外公开、不随用户变化**的内容。
 * 任何"我的余额/我的课表/我的实名"都不得出现在这里（见 `KNOWLEDGE_DENY_LIST`）。
 *
 * 版本：`BUILTIN_KNOWLEDGE_VERSION` 变化会体现在检索结果里，便于排查"答案为何变了"。
 */
export const BUILTIN_KNOWLEDGE_VERSION = '2026-10-17';

function guide(
  id: string,
  title: string,
  module: string | null,
  body: string,
): KnowledgeDoc {
  return { id: `guide:${id}`, title, body, module, kind: 'guide', updatedAt: BUILTIN_KNOWLEDGE_VERSION };
}

